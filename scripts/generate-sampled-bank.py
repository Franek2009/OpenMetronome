#!/usr/bin/env python3
"""Embed accepted canonical WAV pairs without Android/file IO during rendering.
Run after preparing review files. --check compares rather than rewrites output.
"""
import argparse
import base64
import hashlib
import json
import struct
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PREVIEWS = ROOT / 'assets/samples/previews'
TARGET = ROOT / 'app/src/main/kotlin/org/openmetronome/domain/audio/SampledClickBank.kt'
VOICES = [('SAMPLE_NATURAL', '01-natural'), ('SAMPLE_SHORT', '02-short'), ('SAMPLE_LOW', '03-low')]


def generate():
    approved = {a['file']: a['sha256'] for a in json.loads((PREVIEWS / 'measurements.json').read_text())}
    entries = []
    for sound, prefix in VOICES:
        pair = []
        for role in ('normal', 'accent'):
            path = PREVIEWS / f'{prefix}-{role}.wav'
            assert hashlib.sha256(path.read_bytes()).hexdigest() == approved[path.name]
            with wave.open(str(path)) as wav:
                assert (wav.getnchannels(), wav.getsampwidth(), wav.getframerate()) == (1, 2, 48000)
                assert wav.getnframes() <= 1920
                raw = wav.readframes(wav.getnframes())
            pcm = struct.unpack('<' + 'h' * (len(raw)//2), raw)
            assert pcm[0] == pcm[-1] == 0 and max(map(abs, pcm)) == 29162
            assert abs(sum(pcm)/len(pcm)) < 1
            pair.append(base64.b64encode(raw).decode())
        entries.append(f'        ClickSound.{sound} to (decode("{pair[0]}") to decode("{pair[1]}"))')
    return '''// Generated by scripts/generate-sampled-bank.py; see assets/samples/PROVENANCE.md.
package org.openmetronome.domain.audio

import java.nio.ByteBuffer
import java.nio.ByteOrder
import java.util.Base64
import org.openmetronome.domain.model.ClickSound

/** Immutable source bank decoded once before rendering; callers receive private PCM arrays. */
internal object SampledClickBank {
    private fun decode(encoded: String): ShortArray {
        val bytes = ByteBuffer.wrap(Base64.getDecoder().decode(encoded)).order(ByteOrder.LITTLE_ENDIAN)
        return ShortArray(bytes.remaining() / 2) { bytes.short }
    }
    private val pairs by lazy {
        mapOf(
''' + ',\n'.join(entries) + '''
        )
    }
    fun generate(rate: Int, accented: Boolean, sound: ClickSound): ShortArray {
        val pair = pairs.getValue(sound)
        // Both source roles were prepared independently; never transpose the accent again.
        return SamplePcm.click(if (accented) pair.second else pair.first, rate, false)
    }
}
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = generate()
    if args.check:
        assert TARGET.read_text() == source, 'Generated bank differs; regenerate and review'
    else:
        TARGET.write_text(source)
    print('PASS: accepted sample bank matches review PCM' if args.check else 'Generated accepted sample bank')
